// Copies the canonical data into the package at build time, so the repository holds one copy of each:
//   ../model/head-v1.json                       -> head-v1.json and src/generated/head.ts
//   ../src/privacy_gate/guard/privacy-v2.json   -> privacy-v2.json and src/generated/rules.ts
//   ../rules/conformance.v2.json                -> test/conformance.v2.json (tests only, not published)
//   ../LICENSE, ../NOTICE                       -> LICENSE, NOTICE (Apache-2.0 asks for both in a redistribution)
// The SHA-256 of each file is the one `privacy-gate info` reports, so a JS caller can log the same identity.
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = dirname(dirname(fileURLToPath(import.meta.url)));
const root = dirname(pkg);
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

const headBytes = readFileSync(join(root, "model", "head-v1.json"));
const rulesBytes = readFileSync(join(root, "src", "privacy_gate", "guard", "privacy-v2.json"));
const head = JSON.parse(headBytes.toString("utf8"));
const rules = JSON.parse(rulesBytes.toString("utf8"));

mkdirSync(join(pkg, "src", "generated"), { recursive: true });
const banner = "// Generated by scripts/generate.mjs from the repository's canonical files. Do not edit.\n";

writeFileSync(
  join(pkg, "src", "generated", "head.ts"),
  banner +
    'import type { HeadFile } from "../types.js";\n\n' +
    `export const HEAD_SHA256 = ${JSON.stringify(sha256(headBytes))};\n\n` +
    `export const HEAD: HeadFile = ${JSON.stringify(head)};\n`,
);
writeFileSync(
  join(pkg, "src", "generated", "rules.ts"),
  banner +
    'import type { RulesFile } from "../types.js";\n\n' +
    `export const RULESET_SHA256 = ${JSON.stringify(sha256(rulesBytes))};\n\n` +
    `export const RULES: RulesFile = ${JSON.stringify(rules)};\n`,
);

copyFileSync(join(root, "model", "head-v1.json"), join(pkg, "head-v1.json"));
copyFileSync(join(root, "src", "privacy_gate", "guard", "privacy-v2.json"), join(pkg, "privacy-v2.json"));
copyFileSync(join(root, "rules", "conformance.v2.json"), join(pkg, "test", "conformance.v2.json"));
copyFileSync(join(root, "LICENSE"), join(pkg, "LICENSE"));
copyFileSync(join(root, "NOTICE"), join(pkg, "NOTICE"));
console.log(`head ${sha256(headBytes).slice(0, 16)}  rules ${rules.id} ${rules.version} ${sha256(rulesBytes).slice(0, 16)}`);
